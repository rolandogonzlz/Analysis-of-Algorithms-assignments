#include <iostream>
#include <vector>
#include <algorithm>

std::vector<int> sieveOfEratosthenes(int n)
{
    std::vector<bool> isPrime(n + 1, true);

    if (n >= 0)
    {
        isPrime[0] = false;
    }

    if (n >= 1)
    {
        isPrime[1] = false;
    }

    for (int p = 2; p * p <= n; p++)
    {
        if (isPrime[p])
        {
            for (int multiple = p * p;
                 multiple <= n;
                 multiple += p)
            {
                isPrime[multiple] = false;
            }
        }
    }

    std::vector<int> primes;

    for (int i = 2; i <= n; i++)
    {
        if (isPrime[i])
        {
            primes.push_back(i);
        }
    }

    return primes;
}

int middleSchoolGCD(int m, int n)
{
    int limit = std::max(m, n);

    std::vector<int> primes = sieveOfEratosthenes(limit);

    int remainingM = m;
    int remainingN = n;

    int gcd = 1;

    for (int prime : primes)
    {
        int exponentM = 0;
        int exponentN = 0;

        while (remainingM % prime == 0)
        {
            exponentM++;
            remainingM /= prime;
        }

        while (remainingN % prime == 0)
        {
            exponentN++;
            remainingN /= prime;
        }

        int commonExponent =
            std::min(exponentM, exponentN);

        for (int i = 0; i < commonExponent; i++)
        {
            gcd *= prime;
        }
    }

    return gcd;
}

int main()
{
    int m;
    int n;

    std::cout << "Enter the first positive integer: ";
    std::cin >> m;

    std::cout << "Enter the second positive integer: ";
    std::cin >> n;

    if (m <= 0 || n <= 0)
    {
        std::cout << "Both numbers must be positive integers.\n";
        return 1;
    }

    std::vector<int> primes =
        sieveOfEratosthenes(std::max(m, n));

    std::cout << "\nPrime numbers generated by the Sieve:\n";

    for (int prime : primes)
    {
        std::cout << prime << " ";
    }

    std::cout << "\n\n";

    int result = middleSchoolGCD(m, n);

    std::cout << "GCD(" << m << ", " << n << ") = "
              << result << '\n';

    return 0;
}